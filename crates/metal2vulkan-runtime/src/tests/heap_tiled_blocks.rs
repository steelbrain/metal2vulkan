/// The rows of `table` (`M4_ROWS`).
fn rows(table: &str) -> Vec<Row> {
    table
        .lines()
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            let fields: Vec<&str> = line.split(' ').collect();
            let [pf, ty, w, h, d, levels, array, size, align, span] = fields[..] else {
                panic!("a row of ten fields: {line}");
            };
            let number = |field: &str| field.parse::<u64>().unwrap();
            Row {
                pf: P::from_name(&format!("MTLPixelFormat{pf}")).unwrap(),
                texture_type: T::from_name(&format!("MTLTextureType{ty}")).unwrap(),
                extent: [number(w), number(h), number(d)],
                levels: levels.parse().unwrap(),
                array: number(array),
                answer: (number(size), number(align)),
                span: u64::from_str_radix(span, 16).unwrap(),
            }
        })
        .collect()
}

impl Row {
    /// Its layout with its blocks placed as `placement` says.
    fn layout(&self, placement: BlockPlacement) -> TiledLayout {
        let unit = u64::from(block_bytes(self.pf).unwrap());
        let block = block_extent(self.pf).unwrap().map(u64::from);
        let slices = match self.texture_type {
            T::Cube | T::CubeArray => 6 * self.array,
            _ => self.array,
        };
        let elements = Elements::Blocks { block, placement };
        let (ty, extent) = (self.texture_type, self.extent);
        TiledLayout::of(unit, elements, ty, extent, self.levels, slices).unwrap()
    }

    /// Its texture: format, type, extent, levels and array length.
    fn shape(&self) -> (P, T, [u64; 3], u32, u64) {
        let (pf, ty, extent) = (self.pf, self.texture_type, self.extent);
        (pf, ty, extent, self.levels, self.array)
    }
}

/// The release's placement of a row's family.
fn placement(pf: P) -> BlockPlacement {
    let family = BlockFamily::of(pf).unwrap_or_else(|| panic!("{pf:?}: no family"));
    heap_blocks(family)
}

/// Every row's answer is the layout's, and every block of it lies where the release's Metal
/// places it, where its CPU copies write it and where its GPU does (a blit's span is its CPU's at
/// every row).
#[test]
fn every_block_lies_where_the_release_places_it() {
    for row in &rows(M4_ROWS) {
        let layout = row.layout(placement(row.pf));
        let (size, align) = row.answer;
        let what = format!("{:?}", row.shape());
        assert_eq!((layout.size, layout.align), (size, align), "{what}");
        assert_eq!(span_hash(&layout, size), row.span, "{what}");
    }
}

/// The rows tell the two placements apart: the other placement misplaces blocks of some row of
/// each family, and answers every row alike (each level allocated alike under both).
